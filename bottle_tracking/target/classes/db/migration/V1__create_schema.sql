CREATE TABLE app_users (
    username VARCHAR(80) PRIMARY KEY,
    password VARCHAR(100) NOT NULL,
    enabled BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE user_authorities (
    username VARCHAR(80) NOT NULL REFERENCES app_users(username) ON DELETE CASCADE,
    authority VARCHAR(80) NOT NULL,
    PRIMARY KEY (username, authority)
);

CREATE TABLE stations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(80) NOT NULL UNIQUE,
    color VARCHAR(30) NOT NULL
);

CREATE TABLE rooms (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(120) NOT NULL UNIQUE,
    station_id BIGINT REFERENCES stations(id)
);

CREATE TABLE bottles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(120) NOT NULL UNIQUE,
    status VARCHAR(30) NOT NULL,
    note VARCHAR(1000),
    current_room_id BIGINT REFERENCES rooms(id)
);

CREATE TABLE bottle_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bottle_id BIGINT NOT NULL REFERENCES bottles(id),
    from_room_id BIGINT,
    to_room_id BIGINT,
    action VARCHAR(40) NOT NULL,
    changed_at TIMESTAMP WITH TIME ZONE NOT NULL,
    changed_by VARCHAR(80) NOT NULL
);
